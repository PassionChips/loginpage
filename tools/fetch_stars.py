#!/usr/bin/env python3
"""Record the GitHub star count of every tool that lists a repository (github=owner/repo).

Writes content/links/github.tsv, which the site reads at startup to show star counts and to sort by
them. Numbers are only ever copied from GitHub, together with the date they were checked.

    python3 -I tools/fetch_stars.py

Uses the GitHub CLI (`gh`) when it is logged in, otherwise GitHub's public API (60 requests an hour).
Archived repositories are reported so they can be reviewed.
"""
import datetime
import json
import pathlib
import shutil
import subprocess
import sys
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parent.parent
DIRECTORY = ROOT / "content" / "links" / "directory.txt"
OUT = ROOT / "content" / "links" / "github.tsv"


def repo_info(repo):
    if shutil.which("gh"):
        proc = subprocess.run(["gh", "api", f"repos/{repo}"], capture_output=True, text=True, timeout=60)
        if proc.returncode == 0:
            return json.loads(proc.stdout)
    req = urllib.request.Request(f"https://api.github.com/repos/{repo}", headers={"Accept": "application/vnd.github+json"})
    with urllib.request.urlopen(req, timeout=20) as resp:
        return json.load(resp)


def main():
    repos = []
    for line in DIRECTORY.read_text(encoding="utf-8").splitlines():
        for part in line.split(" | ")[4:]:
            if part.strip().startswith("github="):
                repos.append(part.strip()[len("github="):])
    today = datetime.date.today().isoformat()
    rows, problems = [], []
    for repo in sorted(set(repos)):
        try:
            info = repo_info(repo)
        except Exception as e:  # missing or renamed repository
            problems.append(f"{repo}: {e}")
            continue
        if info.get("archived"):
            problems.append(f"{repo}: archived")
        rows.append(f"{repo}\t{info['stargazers_count']}")
    OUT.write_text(f"# GitHub stars, checked {today}. Generated by tools/fetch_stars.py; do not edit by hand.\n"
                   + "\n".join(rows) + "\n", encoding="utf-8")
    print(f"wrote {len(rows)} repositories to {OUT.relative_to(ROOT)}")
    for p in problems:
        print("  check:", p)
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
